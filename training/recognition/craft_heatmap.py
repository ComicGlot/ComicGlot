"""
CRAFT Heatmap Visualization Tool

This script extracts and visualizes the heatmaps generated by the CRAFT text 
detection algorithm within EasyOCR. It shows both region and affinity maps 
which represent character regions and connections between them.
"""

import os
import sys
import logging
import cv2
import numpy as np
import torch
import matplotlib.pyplot as plt
from dotenv import load_dotenv
from easyocr import Reader

logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

load_dotenv()

class CraftHeatmapVisualizer:
    """
    Class for extracting and visualizing CRAFT heatmaps from EasyOCR.
    """
    
    def __init__(
        self, 
        language: list = ['ko', 'en'],
        use_gpu: bool = True
    ):
        """
        Initialize the CRAFT heatmap visualizer.
        
        Args:
            language: List of language codes for OCR
            use_gpu: Whether to use GPU for processing
        """
        self.logger = logging.getLogger(self.__class__.__name__)
        self.language = language

        self.device = torch.device('cuda' if torch.cuda.is_available() and use_gpu else 'cpu')
        self.logger.info(f"Using device: {self.device}")

        # Initialize EasyOCR reader with CRAFT detector
        try:
            self.reader = Reader(language, gpu=(self.device.type == 'cuda'), 
                                 detector=True, recognizer=False)
            self.logger.info(f"Initialized CRAFT detector via EasyOCR for languages: {self.language}")
        except Exception as e:
            self.logger.error(f"Failed to initialize EasyOCR: {str(e)}")
            raise
    
    def get_craft_heatmaps(
        self, 
        image_path: str, 
        text_threshold: float = 0.7, 
        link_threshold: float = 0.4, 
        low_text: float = 0.4,
        canvas_size: int = 2560, 
        mag_ratio: float = 1.0,
        show_probs: bool = True
    ):
        """
        Extract CRAFT heatmaps from an image.
        
        Args:
            image_path: Path to the input image
            text_threshold: Text confidence threshold
            link_threshold: Link confidence threshold
            low_text: Text low-bound score
            canvas_size: Maximum image size for inference
            mag_ratio: Image magnification ratio
            show_probs: Whether to show probability maps (True) or binary maps (False)
            
        Returns:
            Dictionary containing original image and heatmaps
        """
        self.logger.info(f"Processing image: {image_path}")
        
        try:

            img = cv2.imread(image_path)
            if img is None:
                raise FileNotFoundError(f"Could not read image: {image_path}")

            detector = self.reader.detector

            from easyocr.craft_utils import getDetBoxes, adjustResultCoordinates
            from easyocr.imgproc import resize_aspect_ratio, normalizeMeanVariance

            img_resized, target_ratio, size_heatmap = resize_aspect_ratio(img, canvas_size, 
                                                                         interpolation=cv2.INTER_LINEAR, 
                                                                         mag_ratio=mag_ratio)
            ratio_h = ratio_w = 1 / target_ratio
            img_resized = normalizeMeanVariance(img_resized)
            img_resized = torch.from_numpy(img_resized).permute(2, 0, 1)  # [h, w, c] to [c, h, w]
            img_resized = img_resized.unsqueeze(0)  # [c, h, w] to [b, c, h, w]
            img_resized = img_resized.to(self.device)
            
            # Forward pass to get score maps
            with torch.no_grad():
                y, feature = detector(img_resized)

            score_text = y[0,:,:,0].cpu().data.numpy()
            score_link = y[0,:,:,1].cpu().data.numpy()

            text_score = score_text.copy()
            link_score = score_link.copy()

            if not show_probs:
                text_score = np.clip(text_score, 0, 1)
                link_score = np.clip(link_score, 0, 1)
                text_score[text_score < text_threshold] = 0
                link_score[link_score < link_threshold] = 0

            score_text_vis = cv2.resize(text_score, (img.shape[1], img.shape[0]))
            score_link_vis = cv2.resize(link_score, (img.shape[1], img.shape[0]))

            if show_probs:
                score_text_colored = (score_text_vis * 255).astype(np.uint8)
                score_link_colored = (score_link_vis * 255).astype(np.uint8)
            else:
                score_text_colored = (score_text_vis * 255).astype(np.uint8)
                score_link_colored = (score_link_vis * 255).astype(np.uint8)
            
            score_text_colored = cv2.applyColorMap(score_text_colored, cv2.COLORMAP_JET)
            score_link_colored = cv2.applyColorMap(score_link_colored, cv2.COLORMAP_JET)

            alpha = 0.5  # Transparency factor
            text_blend = cv2.addWeighted(img, 1 - alpha, score_text_colored, alpha, 0)
            link_blend = cv2.addWeighted(img, 1 - alpha, score_link_colored, alpha, 0)
            
            self.logger.info(f"Successfully extracted CRAFT heatmaps")
            
            return {
                "original_image": img,
                "text_score_map": score_text,
                "link_score_map": score_link,
                "text_heatmap": score_text_colored,
                "link_heatmap": score_link_colored,
                "text_blend": text_blend,
                "link_blend": link_blend
            }
            
        except Exception as e:
            self.logger.error(f"Error extracting CRAFT heatmaps: {str(e)}")
            raise
    
    def visualize_and_save(
        self, 
        heatmaps: dict, 
        output_dir: str = None, 
        base_filename: str = "craft_heatmap"
    ):
        """
        Visualize and save the heatmaps.
        
        Args:
            heatmaps: Dictionary of heatmaps from get_craft_heatmaps
            output_dir: Directory to save visualization images
            base_filename: Base name for output files
        """
        if output_dir:
            os.makedirs(output_dir, exist_ok=True)

        plt.figure(figsize=(18, 12))

        plt.subplot(2, 3, 1)
        plt.imshow(cv2.cvtColor(heatmaps["original_image"], cv2.COLOR_BGR2RGB))
        plt.title("Original Image")
        plt.axis("off")

        plt.subplot(2, 3, 2)
        plt.imshow(cv2.cvtColor(heatmaps["text_heatmap"], cv2.COLOR_BGR2RGB))
        plt.title("Text Region Heatmap")
        plt.axis("off")

        plt.subplot(2, 3, 3)
        plt.imshow(cv2.cvtColor(heatmaps["link_heatmap"], cv2.COLOR_BGR2RGB))
        plt.title("Affinity/Link Heatmap")
        plt.axis("off")

        plt.subplot(2, 3, 5)
        plt.imshow(cv2.cvtColor(heatmaps["text_blend"], cv2.COLOR_BGR2RGB))
        plt.title("Text Heatmap Overlay")
        plt.axis("off")

        plt.subplot(2, 3, 6)
        plt.imshow(cv2.cvtColor(heatmaps["link_blend"], cv2.COLOR_BGR2RGB))
        plt.title("Link Heatmap Overlay")
        plt.axis("off")
        
        plt.tight_layout()

        if output_dir:
            plt_path = os.path.join(output_dir, f"{base_filename}_plot.png")
            plt.savefig(plt_path, dpi=200)
            self.logger.info(f"Saved visualization plot to {plt_path}")
            
            cv2.imwrite(os.path.join(output_dir, f"{base_filename}_text.jpg"), heatmaps["text_heatmap"])
            cv2.imwrite(os.path.join(output_dir, f"{base_filename}_link.jpg"), heatmaps["link_heatmap"])
            cv2.imwrite(os.path.join(output_dir, f"{base_filename}_text_blend.jpg"), heatmaps["text_blend"])
            cv2.imwrite(os.path.join(output_dir, f"{base_filename}_link_blend.jpg"), heatmaps["link_blend"])
        else:
            plt.show()


def main():
    """Main function to run the script."""
    input_bubble = os.path.abspath(os.getenv("INPUT_BUBBLE", "./data/bubbles/test.jpg"))
    output_dir = os.path.abspath(os.getenv("OUTPUT_FOLDER", "./data/output/craft_heatmaps"))
    languages = os.getenv("LANGUAGE", "ko,en").split(',')
    
    logger.info(f"Processing image: {input_bubble}")
    logger.info(f"Output directory: {output_dir}")
    logger.info(f"Languages: {languages}")

    os.makedirs(output_dir, exist_ok=True)

    try:
        visualizer = CraftHeatmapVisualizer(language=languages)

        heatmaps = visualizer.get_craft_heatmaps(
            input_bubble,
            text_threshold=0.7, 
            link_threshold=0.4,
            show_probs=True  # Set to False for binary maps
        )
        
        image_name = os.path.splitext(os.path.basename(input_bubble))[0]
        visualizer.visualize_and_save(
            heatmaps, 
            output_dir=output_dir,
            base_filename=image_name
        )
        
        logger.info("CRAFT heatmap visualization completed successfully")
        
    except Exception as e:
        logger.error(f"Error during heatmap visualization: {str(e)}")
        import traceback
        traceback.print_exc()
        return 1
    
    return 0


if __name__ == "__main__":
    sys.exit(main())